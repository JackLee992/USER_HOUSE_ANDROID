export function gameArtworkIconV2HTML(id) {
  const art = Object.prototype.hasOwnProperty.call(GAME_ICON_ART_V2, id) ? GAME_ICON_ART_V2[id] : null;
  if (!art) return '';
  const [x, y, width, height] = art.sourceRect;
  const [sheetWidth, sheetHeight] = art.sourceSize;
  const sizeX = 100 * sheetWidth / width;
  const sizeY = 100 * sheetHeight / height;
  const posX = sheetWidth === width ? 0 : 100 * x / (sheetWidth - width);
  const posY = sheetHeight === height ? 0 : 100 * y / (sheetHeight - height);
  const url = new URL('../' + art.path, import.meta.url).href;
  return '<div class="wb-game-icon wanba-game-icon-v2" aria-hidden="true" data-icon-art="2" data-icon-game="' + id + '" style="--wanba-icon-image:url(&quot;' + url + '&quot;);--wanba-icon-size:' + sizeX + '% ' + sizeY + '%;--wanba-icon-position:' + posX + '% ' + posY + '%"></div>';
}
